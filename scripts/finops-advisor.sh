#!/usr/bin/env bash
# Runs the FinOps advisor against the live platform.
#   check : CI mode. Asserts the demo tenants get the expected recommendations, then reverts the edits.
#   pr    : scheduled mode. AI write-up, opens a pull request, and triggers CI on it.
# Every proposed manifest is first validated by Gatekeeper on the live cluster (server-side dry-run).
set -euo pipefail
MODE="${1:-check}"
WINDOW="${FINOPS_WINDOW:-5m}"
cd "$(dirname "$0")/.."
# shellcheck source=scripts/prom-lib.sh
source scripts/prom-lib.sh
prom_forward; trap 'kill ${PROM_PF:-0} 2>/dev/null || true' EXIT

echo "==> Client connections by role (debug)"
curl -sfG "${PROM_URL}/api/v1/query" --data-urlencode \
  'query=sum by (namespace, datname, usename) (cnpg_backends_total{datname!~"postgres|template.*"})' \
  | jq -r '.data.result[] | "    \(.metric.namespace)/\(.metric.datname) \(.metric.usename): \(.value[1])"' || true
echo "==> Waiting for enough usage data (>= 20 samples per database)"
for _ in $(seq 1 60); do
  min=$(prom_value 'min(sum by (namespace) (count_over_time(cnpg_collector_up['"$WINDOW"'])))')
  [[ -n "$min" ]] && awk "BEGIN{exit !($min >= 20)}" && break
  sleep 10
done
echo "    min samples: ${min:-0}"

AI_FLAG=(); [[ "$MODE" == pr ]] && AI_FLAG=(--ai)
PYTHONPATH=tools/finops-advisor python3 -m finops_advisor --prometheus "$PROM_URL" --window "$WINDOW" \
  --repo . --out finops-out --apply "${AI_FLAG[@]}" >/dev/null

mapfile -t CHANGED < <(jq -r '.changed_files[]' finops-out/findings.json)
ACCEPTED=(); : >finops-out/blocked.txt
{ echo; echo "#### Guardrail check of every proposal (Gatekeeper on the live cluster, server-side dry-run)"; echo; } >>finops-out/report.md
for f in "${CHANGED[@]}"; do
  ns=$(cut -d/ -f3 <<<"$f")   # gitops/tenants/<namespace>/database.yaml
  if out=$(kubectl apply --dry-run=server -n "$ns" -f "$f" 2>&1); then
    echo "- ✅ \`$f\` accepted" >>finops-out/report.md
    ACCEPTED+=("$f")
  else
    reason=$(sed -n 's/.*denied the request: //p' <<<"$out" | head -1)
    echo "- ⛔ \`$f\` held back, needs owner approval: ${reason:-$out}" >>finops-out/report.md
    echo "$ns" >>finops-out/blocked.txt
    git checkout -- "$f"   # never propose a change the guardrails reject
  fi
done
cat finops-out/report.md >>"${GITHUB_STEP_SUMMARY:-/dev/stdout}"
cat finops-out/report.md

if [[ "$MODE" == check ]]; then
  git checkout -- gitops/tenants
  # Demo expectations: idle dev DB -> hibernate; over-provisioned dev DB -> small (accepted by the guardrails);
  # prod is never hibernated or shrunk on short windows, and any prod upsize must be flagged for review and,
  # because it exceeds the orders budget, held back by Gatekeeper.
  jq -e '
    (.findings[] | select(.database=="inventory-db") | .action) == "hibernate" and
    (.findings[] | select(.database=="analytics-db") | [.action, .proposed_tier]) == ["downsize","small"] and
    (.findings[] | select(.database=="orders-db") | (.action == "none" or (.action == "upsize" and .needs_human_review)))
  ' finops-out/findings.json >/dev/null || { echo "::error::unexpected FinOps recommendations"; exit 1; }
  grep -qx analytics finops-out/blocked.txt && { echo "::error::analytics downsize should pass the guardrails"; exit 1; }
  grep -qx inventory finops-out/blocked.txt && { echo "::error::inventory hibernation should pass the guardrails"; exit 1; }
  if jq -e '.findings[] | select(.database=="orders-db") | .action == "upsize"' finops-out/findings.json >/dev/null; then
    grep -qx orders finops-out/blocked.txt || { echo "::error::over-budget prod upsize was not blocked"; exit 1; }
  fi
  echo "FinOps advisor: expected recommendations and guardrail outcomes ✓"
  exit 0
fi

# ---- pr mode
[[ ${#ACCEPTED[@]} -gt 0 ]] || { echo "Nothing the guardrails accept to propose."; exit 0; }
BRANCH="finops/advisor-$(date -u +%Y%m%d-%H%M)"
TOTAL=$(jq -r '.total_monthly_saving' finops-out/findings.json)
git config user.name "keystone-finops-advisor[bot]"
git config user.email "keystone-finops-advisor@users.noreply.github.com"
# Base the proposal on the latest main (main may have moved while we were measuring); otherwise the branch
# would appear to modify files that changed on main since checkout, workflows included.
git diff -- "${ACCEPTED[@]}" > /tmp/finops.patch
git checkout -- gitops/tenants
git fetch --quiet origin main
git switch -c "$BRANCH" origin/main
git apply --3way /tmp/finops.patch
git add "${ACCEPTED[@]}"
git commit -m "FinOps: right-size databases (save \$${TOTAL}/month)" -m "Generated by the Keystone FinOps advisor."
git push origin "$BRANCH"
gh pr create --title "FinOps: right-size databases, save \$${TOTAL}/month" --body-file finops-out/report.md \
  --base main --head "$BRANCH"
# Pull requests opened with GITHUB_TOKEN do not trigger workflows; dispatch the guardrail CI explicitly.
gh workflow run ci.yml --ref "$BRANCH"
