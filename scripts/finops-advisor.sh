#!/usr/bin/env bash
# Runs the FinOps advisor against the live platform.
#   check : CI mode. Asserts the demo tenants get the expected recommendations, then reverts the edits.
#   pr    : scheduled mode. AI write-up, opens a pull request, and triggers CI on it.
# Every proposed manifest is first validated by Gatekeeper on the live cluster (server-side dry-run).
set -euo pipefail
MODE="${1:-check}"
WINDOW="${FINOPS_WINDOW:-5m}"
cd "$(dirname "$0")/.."
# shellcheck source=scripts/prom-lib.sh
source scripts/prom-lib.sh
prom_forward; trap 'kill ${PROM_PF:-0} 2>/dev/null || true' EXIT

echo "==> Waiting for enough usage data (>= 20 samples per database)"
for _ in $(seq 1 60); do
  min=$(prom_value 'min(sum by (namespace) (count_over_time(cnpg_collector_up['"$WINDOW"'])))')
  [[ -n "$min" ]] && awk "BEGIN{exit !($min >= 20)}" && break
  sleep 10
done
echo "    min samples: ${min:-0}"

AI_FLAG=(); [[ "$MODE" == pr ]] && AI_FLAG=(--ai)
PYTHONPATH=tools/finops-advisor python3 -m finops_advisor --prometheus "$PROM_URL" --window "$WINDOW" \
  --repo . --out finops-out --apply "${AI_FLAG[@]}" >/dev/null

mapfile -t CHANGED < <(jq -r '.changed_files[]' finops-out/findings.json)
VALID=0
{ echo; echo "#### Guardrail check of the proposed changes (Gatekeeper, server-side dry-run)"; echo; } >>finops-out/report.md
for f in "${CHANGED[@]}"; do
  if out=$(kubectl apply --dry-run=server -f "$f" 2>&1); then
    echo "- ✅ \`$f\` accepted" >>finops-out/report.md
  else
    echo "- ⛔ \`$f\` rejected: $(sed -n 's/.*denied the request: //p' <<<"$out" | head -1)" >>finops-out/report.md
    VALID=1
  fi
done
cat finops-out/report.md >>"${GITHUB_STEP_SUMMARY:-/dev/stdout}"
cat finops-out/report.md

if [[ "$MODE" == check ]]; then
  git checkout -- gitops/tenants
  jq -e '
    (.findings[] | select(.database=="inventory-db") | .action) == "hibernate" and
    (.findings[] | select(.database=="analytics-db") | [.action, .proposed_tier]) == ["downsize","small"] and
    (.findings[] | select(.database=="orders-db") | .action) == "none"
  ' finops-out/findings.json >/dev/null || { echo "::error::unexpected FinOps recommendations"; exit 1; }
  echo "FinOps advisor: expected recommendations ✓"
  exit "$VALID"
fi

# ---- pr mode
[[ "$VALID" -eq 0 ]] || { echo "::error::a proposed change was rejected by the guardrails; not opening a PR"; exit 1; }
[[ ${#CHANGED[@]} -gt 0 ]] || { echo "Nothing to change."; exit 0; }
BRANCH="finops/advisor-$(date -u +%Y%m%d-%H%M)"
TOTAL=$(jq -r '.total_monthly_saving' finops-out/findings.json)
git config user.name "keystone-finops-advisor[bot]"
git config user.email "keystone-finops-advisor@users.noreply.github.com"
git switch -c "$BRANCH"
git add "${CHANGED[@]}"
git commit -m "FinOps: right-size databases (save \$${TOTAL}/month)" -m "Generated by the Keystone FinOps advisor."
git push origin "$BRANCH"
gh pr create --title "FinOps: right-size databases, save \$${TOTAL}/month" --body-file finops-out/report.md \
  --base main --head "$BRANCH"
# Pull requests opened with GITHUB_TOKEN do not trigger workflows; dispatch the guardrail CI explicitly.
gh workflow run ci.yml --ref "$BRANCH"
